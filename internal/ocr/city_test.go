package ocr

import "testing"

// Город с одной неверной буквой узнаётся («МООКВА» — Майн Рид, «Оцеола», 1983), короткий и
// непохожий — нет.
func TestCityOf(t *testing.T) {
	for in, want := range map[string]string{
		"МООКВА":      "Москва",
		"Москва":      "Москва",
		"М.":          "Москва",
		"ЛЕНИНГРАЛ":   "Ленинград",
		"Киев":        "Киев",
		"Кнев":        "", // короче пяти букв — только точно
		"МЕТАЛЛУРГИЯ": "",
		"Мосты":       "",
	} {
		got, ok := cityOf(in)
		if got != want || ok != (want != "") {
			t.Errorf("cityOf(%q) = %q, %v; ждали %q", in, got, ok, want)
		}
	}
}
