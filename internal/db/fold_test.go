package db

import "testing"

func TestFoldOldOrthography(t *testing.T) {
	for in, want := range map[string]string{
		"Мастер и Маргарита":    "мастер и маргарита",
		"Ёлка":                  "елка",
		"Повѣсти Бѣлкина":       "повести белкина",
		"МИРЪ":                  "мир",
		"Война и миръ.":         "война и мир.",
		"Исторія Россіи":        "история россии",
		"Ѳеодоръ Достоевскій":   "феодор достоевский", // старое написание имени — так и остаётся
		"Ѳедоръ":                "федор",
		"мѵро":                  "миро",
		"объём, подъезд, съезд": "объем, подъезд, съезд", // ъ внутри слова остаётся
		"Докторъ Живаго":        "доктор живаго",         // окончание -аго не трогаем: фамилия
		"":                      "",
		"ISBN 0-306-40615-2":    "isbn 0-306-40615-2",
	} {
		if got := Fold(in); got != want {
			t.Errorf("Fold(%q) = %q, want %q", in, got, want)
		}
	}
	// одно и то же слово в старой и новой орфографии сводится к одному
	if Fold("Миръ") != Fold("мир") || Fold("Ѳедоръ") != Fold("Федор") {
		t.Error("старая и новая орфография не совпали")
	}
}
