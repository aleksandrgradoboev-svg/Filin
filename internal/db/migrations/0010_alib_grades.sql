-- Шкала состояния — принятая на alib.ru (решено 08.11.2026; alib.ru/sellers.phtml, «Состояние
-- букинистической книги»): плохое, удовлетворительное, хорошее, очень хорошее, отличное,
-- идеальное. Прежние пять ступеней совпадают с нижними пятью alib слово в слово, поэтому
-- значения 1–5 не пересчитываются; добавляется 6 — «идеальное».
--
-- Ограничение 1–5 SQLite на месте не меняет, а пересобрать book_copy нельзя: миграция идёт
-- в транзакции с включёнными внешними ключами, и DROP TABLE каскадом стёр бы выдачи и
-- оценки. Поэтому колонка меняется сама: новая → перелить → старую убрать → переименовать.
-- На grade нет ни индексов, ни триггеров, а запросы называют колонки по именам.
ALTER TABLE book_copy ADD COLUMN grade_alib INTEGER CHECK (grade_alib BETWEEN 1 AND 6);
UPDATE book_copy SET grade_alib = grade;
ALTER TABLE book_copy DROP COLUMN grade;
ALTER TABLE book_copy RENAME COLUMN grade_alib TO grade;
